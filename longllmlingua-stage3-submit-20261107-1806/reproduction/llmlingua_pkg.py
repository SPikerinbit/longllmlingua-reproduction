"""Materialise the pinned vendored LLMLingua reference as an importable package.

The repository stores the upstream file as ``prompt_compressor.py.reference`` so
that provenance stays explicit and the module is never imported by accident.  The
stage-two adapter needs the real module, so it is assembled from those reference
copies under ``cache/vendor/llmlingua_pkg/`` (git-ignored).  Nothing is downloaded
and no second copy is committed; the bytes come from the same pinned commit that
``manifests/resources.json`` records.
"""

from __future__ import annotations

import hashlib
import importlib
import sys
from pathlib import Path

from .common import ROOT

REFERENCE_DIR = ROOT / "vendor/llmlingua_reference/llmlingua"
# ``__init__.py`` is not copied: the upstream one imports ``.version``, which is not
# part of this vendored slice, so a minimal package marker is generated instead.
MODULE_FILES = {
    "prompt_compressor.py": "prompt_compressor.py.reference",
    "utils.py": "utils.py.reference",
}
PACKAGE_MARKER = "# Generated by reproduction.llmlingua_pkg from the pinned vendored reference.\n"


def materialize(target: Path | None = None) -> Path:
    """Copy the pinned reference files into an importable ``llmlingua`` package."""
    package = Path(target or ROOT / "cache/vendor/llmlingua_pkg") / "llmlingua"
    package.mkdir(parents=True, exist_ok=True)
    for name, source in MODULE_FILES.items():
        data = (REFERENCE_DIR / source).read_bytes()
        destination = package / name
        if (not destination.exists()
                or hashlib.sha256(destination.read_bytes()).hexdigest()
                != hashlib.sha256(data).hexdigest()):
            destination.write_bytes(data)
    marker = package / "__init__.py"
    if not marker.exists() or marker.read_text(encoding="utf-8") != PACKAGE_MARKER:
        marker.write_text(PACKAGE_MARKER, encoding="utf-8")
    return package


def load_prompt_compressor(target: Path | None = None):
    """Import and return the pinned ``PromptCompressor`` class."""
    package = materialize(target)
    parent = str(package.parent)
    if parent not in sys.path:
        sys.path.insert(0, parent)
    module = importlib.import_module("llmlingua.prompt_compressor")
    return module.PromptCompressor
